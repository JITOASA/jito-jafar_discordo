/**
 * Gets a random valid (Letter, Category) pair that has verified answers in our database.
 */
export function getRandomHarfRound() {
  const categoriesShuffled = [...CATEGORIES].sort(() => 0.5 - Math.random());
  
  for (const cat of categoriesShuffled) {
    const letterMap = HARF_DATABASE[cat.id];
    if (!letterMap) continue;

    // Filter letters that have at least 1 verified answer
    const validLetters = Object.keys(letterMap).filter(l => letterMap[l] && letterMap[l].length > 0);
    if (validLetters.length === 0) continue;

    const randomLetter = validLetters[Math.floor(Math.random() * validLetters.length)];
    const validAnswers = letterMap[randomLetter];

    return {
      category: cat,
      letter: randomLetter,
      validAnswers: validAnswers || [],
    };
  }

  // Safe fallback
  return {
    category: CATEGORIES[0],
    letter: 'م',
    validAnswers: HARF_DATABASE.animal['م'],
  };
}

